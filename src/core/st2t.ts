// Simplified → Traditional safety net for the free MT engines.
//
// Google/Microsoft usually honor zh-TW/zh-Hant, but simplified characters leak
// through often enough to be visible (mixed-script output). When the target is
// Traditional, the final free-engine text passes through `toTraditional()` as a
// last step — glossary correction runs first, this only cleans up leftovers.
//
// Three layers:
//   1. PHRASES — ambiguous simplifications where one char maps to several
//      traditional ones depending on the word (发→發/髮, 干→幹/乾, …).
//   2. CHARS — one-to-one high-frequency mappings (single pass).
//   3. PROTECTED — words whose simplified form is already correct traditional.
// Phrases and protected words are stashed behind private-use placeholders so
// the char layer can't mangle them (征服 must NOT become 徵服).
//
// Design rule for ambiguous (one-simplified→many-traditional) chars: the CHARS
// default must be the reading that's correct in the most frequent words. When
// BOTH readings appear in high-frequency words (面: 介面/裡面 vs 麵條/泡麵;
// 系: 系統/體系 vs 關係), there is NO safe default — the char is left alone and
// resolved purely by phrases. A leaked simplified char is a minor blemish; a
// wrong traditional char (介麵, 係統) is an active error, so when in doubt we
// keep the char unchanged.
//
// This is a safety net, not a full OpenCC replacement: it covers the common
// cases.

