// Fast lookup: has() check before building output.
const CHAR_MAP = new Map<string, string>(Object.entries(CHARS));

/** Convert simplified Chinese characters to traditional. Idempotent on traditional text. */
export function toTraditional(text: string): string {
  if (!text) return text;
  // Stash protected words AND phrase replacements behind private-use
  // placeholders, so the char layer can't mangle them (征服 must NOT become
  // 徵服; 長征's 征 must survive too).
  const stash: string[] = [];
  const stashOf = (s: string): string => {
    const token = `\uE000${stash.length}\uE001`;
    stash.push(s);
    return token;
  };
  let out = text;
  for (const p of PROTECTED) {
    if (out.includes(p)) out = out.split(p).join(stashOf(p));
  }
  for (const [simp, trad] of PHRASES) {
    if (out.includes(simp)) out = out.split(simp).join(stashOf(trad));
  }
  // Char layer: single pass, skip quickly when nothing matches.
  let hasSimp = false;
  for (const ch of out) {
    if (CHAR_MAP.has(ch)) { hasSimp = true; break; }
  }
  if (hasSimp) out = [...out].map((ch) => CHAR_MAP.get(ch) ?? ch).join('');
  // Restore stashed words.
  for (let i = 0; i < stash.length; i++) {
    out = out.split(`\uE000${i}\uE001`).join(stash[i]);
  }
  return out;
}
