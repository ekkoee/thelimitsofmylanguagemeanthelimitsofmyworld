const catalogs: Record<UiLang, Table> = {
  'zh-TW': zhTW,
  'zh-CN': zhCN,
  en,
  ja,
  ko,
  de,
  fr,
  es,
};

let current: UiLang = 'zh-TW';

export function resolveUiLang(pref: string, nav = 'en'): UiLang {
  const want = (pref || '').trim();
  if ((UI_FIXED as { id: string }[]).some((item) => item.id === want)) return want as UiLang;
  const tag = (nav || 'en').toLowerCase();
  if (tag.startsWith('zh')) {
    if (tag.includes('hant') || tag.includes('tw') || tag.includes('hk') || tag.includes('mo')) return 'zh-TW';
    return 'zh-CN';
  }
  if (tag.startsWith('ja')) return 'ja';
  if (tag.startsWith('ko')) return 'ko';
  if (tag.startsWith('de')) return 'de';
  if (tag.startsWith('fr')) return 'fr';
  if (tag.startsWith('es')) return 'es';
  if (tag.startsWith('en')) return 'en';
  return 'en';
}

export function setUiLang(pref: string, nav?: string): UiLang {
  const navLang = nav ?? (typeof navigator !== 'undefined' ? navigator.language : 'en');
  current = resolveUiLang(pref, navLang);
  return current;
}

export function getUiLang(): UiLang {
  return current;
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  const table = catalogs[current] || catalogs.en;
  let text = table[key] || catalogs['zh-TW'][key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function applyI18n(root: ParentNode = typeof document !== 'undefined' ? document : undefined as unknown as ParentNode): void {
  if (!root || typeof document === 'undefined') return;
  document.documentElement.lang = current;
  root.querySelectorAll<HTMLElement>('[data-i18n], [data-i18n-aria], [data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18n as MsgKey | undefined;
    if (key && key in catalogs['zh-TW']) el.textContent = t(key);
    const aria = el.dataset.i18nAria as MsgKey | undefined;
    if (aria && aria in catalogs['zh-TW']) el.setAttribute('aria-label', t(aria));
    const placeholder = el.dataset.i18nPlaceholder as MsgKey | undefined;
    if (placeholder && placeholder in catalogs['zh-TW'] && 'placeholder' in el) {
      (el as HTMLInputElement).placeholder = t(placeholder);
    }
  });
}

let watching = false;
export function watchUiLang(): void {
  if (watching) return;
  const chromeObj = (globalThis as { chrome?: typeof chrome }).chrome;
  if (!chromeObj?.storage?.onChanged) return;
  watching = true;
  chromeObj.storage.onChanged.addListener((changes, area) => {
    if (area !== 'sync' || !changes.ibt_settings) return;
    const next = (changes.ibt_settings.newValue as { uiLang?: string } | undefined)?.uiLang || '';
    const prev = (changes.ibt_settings.oldValue as { uiLang?: string } | undefined)?.uiLang || '';
    if (next === prev) return;
    setUiLang(next);
    applyI18n();
  });
}
